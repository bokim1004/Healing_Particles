// 감정 → 초기 색상 + 치유 색상
export const getEmotionPalette = (emotion) => {
    const text = emotion.toLowerCase();

    // 화남/분노
    if (text.match(/화|분노|짜증|열받|angry|mad|furious/)) {
        return {
            name: "분노",
            positive: false,
            initial: [
                [1.0, 0.2, 0.2],
                [1.0, 0.3, 0.1],
                [0.9, 0.1, 0.2],
                [1.0, 0.4, 0.2],
                [0.8, 0.15, 0.15],
            ],
            healed: [
                [1.0, 0.7, 0.4],
                [1.0, 0.8, 0.5],
                [1.0, 0.75, 0.45],
                [0.95, 0.7, 0.5],
                [1.0, 0.85, 0.55],
            ]
        };
    }

    // 슬픔/우울
    if (text.match(/슬|우울|외로|쓸쓸|sad|lonely|depressed|blue/)) {
        return {
            name: "슬픔",
            positive: false,
            initial: [
                [0.2, 0.4, 0.7],
                [0.3, 0.5, 0.8],
                [0.1, 0.3, 0.6],
                [0.4, 0.6, 0.9],
                [0.2, 0.3, 0.5],
            ],
            healed: [
                [0.9, 0.8, 0.6],
                [1.0, 0.85, 0.65],
                [0.95, 0.75, 0.55],
                [1.0, 0.9, 0.7],
                [0.9, 0.7, 0.5],
            ]
        };
    }

    // 불안/긴장
    if (text.match(/불안|긴장|초조|두려|무서|anxiety|fear|nervous|scared/)) {
        return {
            name: "불안",
            positive: false,
            initial: [
                [0.5, 0.2, 0.7],
                [0.6, 0.3, 0.8],
                [0.4, 0.1, 0.6],
                [0.7, 0.4, 0.9],
                [0.3, 0.15, 0.5],
            ],
            healed: [
                [0.8, 0.7, 0.6],
                [0.9, 0.8, 0.7],
                [0.85, 0.75, 0.65],
                [0.95, 0.85, 0.75],
                [0.8, 0.7, 0.6],
            ]
        };
    }

    // 피곤/지침
    if (text.match(/피곤|지침|힘듦|tired|exhausted|weary/)) {
        return {
            name: "피로",
            positive: false,
            initial: [
                [0.5, 0.5, 0.5],
                [0.6, 0.6, 0.6],
                [0.4, 0.4, 0.5],
                [0.55, 0.55, 0.6],
                [0.45, 0.45, 0.45],
            ],
            healed: [
                [1.0, 0.9, 0.7],
                [1.0, 0.85, 0.65],
                [0.95, 0.8, 0.6],
                [1.0, 0.95, 0.75],
                [0.9, 0.85, 0.7],
            ]
        };
    }

    // 평화/행복 (이미 좋은 감정)
    return {
        name: "평화",
        positive: true,
        initial: [
            [1.0, 0.85, 0.5],
            [1.0, 0.9, 0.6],
            [0.95, 0.8, 0.45],
            [1.0, 0.95, 0.65],
            [0.9, 0.75, 0.4],
        ],
        healed: [
            [1.0, 0.95, 0.7],
            [1.0, 0.98, 0.8],
            [0.98, 0.9, 0.65],
            [1.0, 1.0, 0.85],
            [0.95, 0.85, 0.6],
        ]
    };
};
